function build() {
  const groups = [];
  const all = [];
  for (const script of ['h', 'k']) {
    for (const g of GROUPS) {
      const items = ROWS[g].map(([kana, ro, ko]) => {
        const k = script === 'h' ? kana : toKata(kana);
        return { id: `${script}:${k}`, type: 'kana', level: 'kana', k, ro, ko, script, group: g };
      });
      const name = script === 'h' ? `히라가나 ${GROUP_NAME[g]}` : `가타카나 ${toKata(GROUP_NAME[g])}`;
      groups.push({ id: `${script}-${g}`, script, name, tip: TIPS[g], items });
      all.push(...items);
    }
    if (script === 'k') {
      const items = EXTRA_KATA.map(([k, ro, ko]) => ({ id: `k:${k}`, type: 'kana', level: 'kana', k, ro, ko, script: 'k', group: 'kx' }));
      groups.push({ id: 'k-kx', script: 'k', name: `가타카나 ${GROUP_NAME.kx}`, tip: TIPS.kx, items });
      all.push(...items);
    }
  }
  return { groups, all };
}

export const KANA = build();
export const KANA_BY_ID = new Map(KANA.all.map((k) => [k.id, k]));
